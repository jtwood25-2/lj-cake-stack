"""Build every deployable copy of the game from game.html, the single source.

    python build.py

Outputs (all generated; edit game.html, admin.html or worker/index.js instead):
    index.html          GitHub Pages copy. No score server, so scores stay on each device.
    public/index.html   Cloudflare copy. Talks to the score server at /api.
    public/admin.html   Score moderation page, served at /admin.
    worker/core.js      The game's scoring core, for the server to replay runs with.

game.html is page content only (no <html>/<head>), because the claude.ai preview adds its own.
"""
import argparse
import json
import pathlib
import re
import shutil
import sys

HEAD = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
<meta name="theme-color" content="#121a2c">
<meta name="description" content="Stack Lauren and Jackson's wedding cake as high as you can.">
<meta property="og:title" content="Cake Stack · Lauren &amp; Jackson">
<meta property="og:description" content="Stack the wedding cake as high as you can. Beat the family.">
<meta property="og:type" content="website">
<style>[hidden]{display:none!important}:root{padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}</style>
</head>
<body>
"""
TAIL = "\n</body>\n</html>\n"
API_LINE = 'const API_BASE = "";'


def fail(msg):
    print(json.dumps({"error": msg}))
    sys.exit(1)


def main():
    argparse.ArgumentParser(description=__doc__.splitlines()[0]).parse_args()
    here = pathlib.Path(__file__).parent
    try:
        body = (here / "game.html").read_text(encoding="utf-8")
    except OSError as e:
        fail(str(e))
    if "<html" in body.lower():
        fail("game.html must be page content only, without <html>")
    if body.count(API_LINE) != 1:
        fail(f"expected exactly one line `{API_LINE}` in game.html")
    core = re.search(r"CORE-BEGIN.*?\*/(.*?)/\* =+ CORE-END", body, re.S)
    if not core:
        fail("CORE-BEGIN / CORE-END markers not found in game.html")

    wrote = {}
    def put(rel, text):
        p = here / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
        wrote[rel] = len(text)

    put("index.html", HEAD + body + TAIL)
    put("public/index.html", HEAD + body.replace(API_LINE, 'const API_BASE = "/api";') + TAIL)
    shutil.copyfile(here / "admin.html", here / "public/admin.html")
    wrote["public/admin.html"] = (here / "public/admin.html").stat().st_size
    put("worker/core.js",
        "// GENERATED by build.py from the CORE block of game.html. Do not edit.\n"
        + core.group(1).strip() + "\n\nexport { replay, step, newGame, posAt };\n")
    print(json.dumps({"wrote": wrote}))


if __name__ == "__main__":
    main()
